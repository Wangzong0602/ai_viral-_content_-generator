"""
敏感词检查服务：基础质量检查

【为什么要敏感词过滤？】
内容平台对违规内容（涉政、色情、暴力等）零容忍，
发布带敏感词的内容会导致账号限流甚至封号。
所以生成内容在"最终交给用户"前，先做一道基础安检。

【MVP 阶段的实现方式】
用一个"基础敏感词列表"做关键词匹配。
- 优点：零成本、快、无网络依赖
- 缺点：词库有限（完整方案需要接入第三方审核 API，见扩展功能）

【将来如何增强？】
- 词库存数据库/文件，后台可维护（P2 扩展）
- 接入阿里云内容安全等第三方审核 API（P0 扩展）
"""

# 基础敏感词库（演示用，仅覆盖常见违禁词类别）
# 真实项目应从配置文件/数据库加载更全面的词库
SENSITIVE_WORDS = [
    "赌博",
    "博彩",
    "色情",
    "裸贷",
    "毒品",
    "枪支",
    "诈骗",
    "刷单",
    "代开发票",
    "办假证",
]


def check_sensitive(content: str) -> dict:
    """
    检查文案是否包含敏感词。

    :param content: 待检查的文案
    :return: 检查报告：
        {"has_sensitive": bool, "words": [命中的敏感词列表]}
    """
    # 遍历词库，找出所有出现在文案中的敏感词
    # 列表推导式：一行完成"筛选"逻辑
    hit_words = [word for word in SENSITIVE_WORDS if word in content]
    return {"has_sensitive": len(hit_words) > 0, "words": hit_words}
